create or replace function public.list_vector_collections(p_owner_id uuid)
returns table (
  id uuid,
  name text,
  embedding_model text,
  vector_dimension integer,
  row_count bigint,
  created_at timestamptz,
  updated_at timestamptz
)
language sql
stable
security invoker
set search_path = public
as $$
  select
    collections.id,
    collections.name,
    collections.embedding_model,
    collections.vector_dimension,
    count(documents.id) as row_count,
    collections.created_at,
    collections.updated_at
  from public.vector_collections as collections
  left join public.vector_documents as documents
    on documents.collection_id = collections.id
   and documents.owner_id = p_owner_id
  where collections.owner_id = p_owner_id
  group by collections.id
  order by collections.updated_at desc;
$$;

create or replace function public.match_vector_documents(
  p_owner_id uuid,
  p_collection_id uuid,
  p_query_embedding extensions.vector(1536),
  p_match_count integer default 5
)
returns table (
  id bigint,
  content text,
  metadata jsonb,
  similarity double precision
)
language sql
stable
security invoker
set search_path = public, extensions
as $$
  select
    documents.id,
    documents.content,
    documents.metadata,
    1 - (documents.embedding <=> p_query_embedding) as similarity
  from public.vector_documents as documents
  where documents.owner_id = p_owner_id
    and documents.collection_id = p_collection_id
  order by documents.embedding <=> p_query_embedding
  limit least(greatest(coalesce(p_match_count, 5), 1), 20);
$$;

